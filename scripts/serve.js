// Tiny local web server for the dashboard (MetaMask does not work on file:// pages).
// Usage: npm run serve   ->  open http://localhost:8080
const http = require("http");
const fs = require("fs");
const path = require("path");

const dir = path.join(__dirname, "..", "docs");
const PORT = 8080;
const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
};

http
  .createServer((req, res) => {
    let urlPath = decodeURIComponent((req.url || "/").split("?")[0]);
    if (urlPath === "/") urlPath = "/index.html";
    const file = path.normalize(path.join(dir, urlPath));
    if (!file.startsWith(dir)) {
      res.writeHead(403);
      return res.end("Forbidden");
    }
    fs.readFile(file, (err, data) => {
      if (err) {
        res.writeHead(404);
        return res.end("Not found");
      }
      res.writeHead(200, {
        "Content-Type": TYPES[path.extname(file)] || "application/octet-stream",
        "Cache-Control": "no-store",
      });
      res.end(data);
    });
  })
  .listen(PORT, () => {
    console.log("Dashboard running: http://localhost:" + PORT);
    console.log("Keep this window open. Press Ctrl+C to stop.");
  });
