// Compiles contracts/AgentLeash.sol with solc-js and writes:
//   build/AgentLeash.json  (abi + bytecode, used by the agent)
//   docs/artifact.js       (same, used by the dashboard's Deploy button)
const fs = require("fs");
const path = require("path");
const solc = require("solc");

const root = path.join(__dirname, "..");
const srcPath = path.join(root, "contracts", "AgentLeash.sol");
const source = fs.readFileSync(srcPath, "utf8");

const input = {
  language: "Solidity",
  sources: { "AgentLeash.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "paris", // no PUSH0 / Cancun opcodes, safest for a new EVM chain
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

console.log("Compiling with solc " + solc.version() + " ...");
const output = JSON.parse(solc.compile(JSON.stringify(input)));

let hasError = false;
for (const e of output.errors || []) {
  if (e.severity === "error") hasError = true;
  console.log((e.severity === "error" ? "ERROR: " : "warning: ") + e.formattedMessage);
}
if (hasError) {
  console.error("\nCompile FAILED. Send this screen to Claude.");
  process.exit(1);
}

const c = output.contracts["AgentLeash.sol"]["AgentLeash"];
const artifact = {
  contractName: "AgentLeash",
  compiler: "solc " + solc.version(),
  settings: { optimizer: true, runs: 200, evmVersion: "paris" },
  abi: c.abi,
  bytecode: "0x" + c.evm.bytecode.object,
};

fs.mkdirSync(path.join(root, "build"), { recursive: true });
fs.writeFileSync(path.join(root, "build", "AgentLeash.json"), JSON.stringify(artifact, null, 2));
fs.writeFileSync(
  path.join(root, "docs", "artifact.js"),
  "// Generated by scripts/compile.js - do not edit\nwindow.AGENTLEASH_ARTIFACT = " +
    JSON.stringify(artifact) +
    ";\n"
);

console.log("OK - compiled. Bytecode size: " + (artifact.bytecode.length - 2) / 2 + " bytes");
console.log("Wrote build/AgentLeash.json and docs/artifact.js");
